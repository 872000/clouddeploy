"""Azure Container Apps deployment generation.

Produces the ``az`` CLI commands and a Bicep template for deploying one
containerized app to Azure Container Apps. Nothing here talks to Azure;
:func:`clouddeploy.deploy.run_commands` executes the commands only when the
user passes ``--execute``.
"""

from __future__ import annotations

import shlex


def _q(value):
    return shlex.quote(str(value))


def azure_commands(cfg):
    """Return the ordered ``az`` CLI commands (as shell strings) that deploy
    the app to Azure Container Apps."""
    app = cfg.app
    az = cfg.require_provider("azure")
    name = az.app_name(app.name)
    env_vars = " ".join(
        f"--env-vars {_q(f'{key}={value}')}" for key, value in app.env.items()
    )
    commands = [
        f"az group create --name {_q(az.resource_group)} --location {_q(az.location)}",
        f"az containerapp env create --name {_q(az.environment)} "
        f"--resource-group {_q(az.resource_group)} --location {_q(az.location)}",
        f"az containerapp create --name {_q(name)} "
        f"--resource-group {_q(az.resource_group)} "
        f"--environment {_q(az.environment)} "
        f"--image {_q(app.image)} --target-port {app.port} "
        f"--cpu {app.cpu} --memory {app.memory} --ingress external "
        f"--min-replicas {app.replicas} --max-replicas {app.replicas}"
        + (f" {env_vars}" if env_vars else ""),
        f"az containerapp show --name {_q(name)} "
        f"--resource-group {_q(az.resource_group)} "
        "--query properties.configuration.ingress.fqdn -o tsv",
    ]
    return commands


def azure_bicep(cfg):
    """Return a Bicep template that creates the environment and container app.

    Deploy it with ``az deployment group create --resource-group <rg>
    --template-file main.bicep`` after pushing the image to a registry the
    app can pull from (e.g. Azure Container Registry).
    """
    app = cfg.app
    az = cfg.require_provider("azure")
    name = az.app_name(app.name)
    env_entries = ",\n".join(
        "        {\n"
        f"          name: '{key}'\n"
        f"          value: '{value}'\n"
        "        }"
        for key, value in app.env.items()
    )
    env_block = f"\n        env: [\n{env_entries}\n        ]" if env_entries else ""
    return f"""// Generated by clouddeploy for app '{app.name}'.
// Deploy with:
//   az deployment group create --resource-group {az.resource_group} \\
//     --template-file main.bicep
// The image must already exist in a registry the Container App can pull
// from (see README: push to Azure Container Registry first).

param location string = '{az.location}'
param environmentName string = '{az.environment}'
param containerAppName string = '{name}'
param containerImage string = '{app.image}'
param targetPort int = {app.port}

resource environment 'Microsoft.App/managedEnvironments@2023-05-01' = {{
  name: environmentName
  location: location
  properties: {{}}
}}

resource containerApp 'Microsoft.App/containerApps@2023-05-01' = {{
  name: containerAppName
  location: location
  properties: {{
    managedEnvironmentId: environment.id
    configuration: {{
      ingress: {{
        external: true
        targetPort: targetPort
      }}
    }}
    template: {{
      containers: [
        {{
          name: containerAppName
          image: containerImage
          resources: {{
            cpu: json('{app.cpu}')
            memory: '{app.memory}'
          }}{env_block}
        }}
      ]
      scale: {{
        minReplicas: {app.replicas}
        maxReplicas: {app.replicas}
      }}
    }}
  }}
}}

output fqdn string = containerApp.properties.configuration.ingress.fqdn
"""
